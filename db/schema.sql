-- UC01: Search instrument — preliminary skeleton only, full model in MS4

CREATE TABLE instrument (
    symbol         VARCHAR(20) PRIMARY KEY,   -- e.g. 'EUR/USD', 'BTC/USD', 'AAPL'
    name           VARCHAR(100) NOT NULL,     -- display name, e.g. 'Apple Inc.'
    exchange       VARCHAR(50),               -- e.g. 'NASDAQ' for stocks; NULL for forex/crypto pairs
    type           VARCHAR(30) NOT NULL CHECK (type IN ('forex', 'crypto', 'stock'))  -- BR1: the app's three supported asset classes
);
-- NAMING: every identifier in this file is snake_case, never camelCase.
-- Postgres folds unquoted identifiers to lowercase, so a column or function
-- written as `someName` silently becomes `somename` in the actual database, and
-- every later reference would need "someName" in double quotes forever.
-- snake_case avoids that entirely, and matches the DB requirements doc.
--
-- REMOVED 2026-09-15: `finnhub_symbol VARCHAR(20)`. It held Finnhub's own
-- spelling of an instrument ('OANDA:EUR_USD', 'BINANCE:BTCUSDT') for the live
-- feed. Demo trading is now BTC/USD only (UC04 BR6), so exactly one Finnhub
-- symbol is ever needed and it lives as a constant in the Java that talks to
-- Finnhub. A column carrying one value for six rows, five of which nothing
-- reads, is not a model of anything. If demo trading ever covers more than one
-- instrument, this column comes back -- along with seed values and the entity
-- field.

CREATE TABLE price_candle (
    symbol      VARCHAR(20) NOT NULL REFERENCES instrument(symbol),
    interval    VARCHAR(10) NOT NULL CHECK (interval IN ('2h', '4h', '1day', '1week')),
    datetime    TIMESTAMP NOT NULL,
    open        NUMERIC(18,5) NOT NULL,
    high        NUMERIC(18,5) NOT NULL,
    low         NUMERIC(18,5) NOT NULL,
    close       NUMERIC(18,5) NOT NULL,
    volume      BIGINT,
    PRIMARY KEY (symbol, interval, datetime)
);
-- Interval strings are fixed to the four the app actually uses, and are spelled
-- the way Twelve Data spells them in its own `interval` request parameter, so the
-- mapping from API response -> stored rows needs no translation.
--
-- The CHECK is deliberate: without it, a single typo ('1d' instead of '1day')
-- inserts happily and then every read for that symbol silently returns zero rows
-- -- which looks exactly like "not ingested yet" and is painful to debug. Drop it
-- if you'd rather keep the column open-ended, but then the four functions below
-- and the ingestion code have to agree on spelling by convention alone.
--
-- Chart range -> interval (SCRUM-61): 1w -> 2h, 1m -> 4h, 6m -> 1day, 1yr -> 1week.


-- UC03/UC04/UC05 (SCRUM-39): accounts. Every user-scoped feature -- watchlist,
-- demo-trading positions and trades, journal entries -- hangs off this table.

CREATE TABLE app_user (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username      VARCHAR(50) NOT NULL UNIQUE,
    password_hash VARCHAR(100) NOT NULL,
    cash_balance  NUMERIC(18,5) NOT NULL DEFAULT 10000.00 CHECK (cash_balance >= 0),
    created_at    TIMESTAMP NOT NULL DEFAULT (NOW() AT TIME ZONE 'UTC')
);
-- Named app_user, not user: `user` is a reserved word in SQL and a built-in
-- function in Postgres (it returns the current role), so an unquoted
-- `CREATE TABLE user` is a syntax error and every later reference would need
-- "user" in double quotes forever -- the same identifier trap as the naming
-- note at the top of this file.
--
-- id is a surrogate key, not the username: usernames are the login handle and a
-- user may one day want to change theirs, which would cascade through every
-- row that references them. Watchlist entries, positions, trades and journal
-- entries (each arriving with its own story) key on this id with
-- REFERENCES app_user(id) ON DELETE CASCADE.
--
-- GENERATED BY DEFAULT rather than ALWAYS so an explicit id can still be given
-- in seed data or a test fixture; Hibernate's IDENTITY strategy never supplies
-- one, so both spellings work for the application itself.
--
-- password_hash holds a hash and NEVER a password. There is deliberately no
-- `password` column anywhere in this schema. A BCrypt hash is exactly 60
-- characters, but Spring Security's DelegatingPasswordEncoder prefixes it with
-- an algorithm tag ("{bcrypt}$2a$10$..."), and swapping the algorithm later
-- would change the length again -- so this is VARCHAR(100), not CHAR(60).
--
-- There is also deliberately no login/verify function in this file. Hashing and
-- verification happen in Java (BCryptPasswordEncoder in the service layer); the
-- database only stores the result. A SQL function that took a plaintext
-- password would put it in the query log and in pg_stat_statements.
--
-- UNIQUE on username is enforced here rather than only by a SELECT-then-INSERT
-- in Java: two concurrent registrations can both pass that check and both
-- insert. The constraint makes the second one fail, which the backend maps to
-- the API's 409. Uniqueness is case-SENSITIVE, so 'Nazir' and 'nazir' are two
-- accounts; if we'd rather they collide, replace UNIQUE with
--   CREATE UNIQUE INDEX app_user_username_lower ON app_user (LOWER(username));
--
-- cash_balance is the virtual demo-trading balance, starting at $10,000
-- (UC04 BR1) -- the default lives here so the rule holds even for a row
-- inserted by hand. NUMERIC(18,5) matches the price columns in price_candle on
-- purpose: cash is debited by price x quantity, and mixing a 5-decimal price
-- with a 2-decimal balance rounds every forex and crypto trade. The
-- CHECK (>= 0) is a backstop only -- "you cannot spend more than you have" is a
-- business rule and belongs in the service layer, where it can produce a
-- readable message instead of a constraint violation.
--
-- created_at is stored in UTC (NOTE 1 below), like the intraday candles.

-- UC03 (SCRUM-22): each user's personal watchlist. A join table and nothing
-- more -- it says which instruments a user has saved, and when.

CREATE TABLE watchlist (
    user_id  BIGINT      NOT NULL REFERENCES app_user(id) ON DELETE CASCADE,
    symbol   VARCHAR(20) NOT NULL REFERENCES instrument(symbol),
    added_at TIMESTAMP   NOT NULL DEFAULT (NOW() AT TIME ZONE 'UTC'),
    PRIMARY KEY (user_id, symbol)
);
-- The composite primary key IS the no-duplicates rule (UC03 BR1). Adding the
-- same instrument twice is not prevented by application code remembering to
-- check -- it is impossible, because the row already exists. A surrogate `id`
-- column here would have broken that: every add would be a new, unique row and
-- the duplicate check would live only in Java, where it can be forgotten or
-- lost to a race. There is also nothing that needs to reference a watchlist
-- row, so the surrogate key would buy nothing in exchange.
--
-- It doubles as the index for the query the app actually runs. "Everything on
-- this user's watchlist" filters on user_id, which is the leading column of the
-- key, so Postgres uses the primary key index for it. No second index needed.
--
-- ON DELETE CASCADE on user_id: deleting an account takes its watchlist rows
-- with it. Without it the rows would be orphaned -- pointing at a user id that
-- no longer exists, invisible to every query, and forever.
--
-- Deliberately NO cascade on symbol. The default (NO ACTION) means deleting an
-- instrument that somebody has saved fails with a constraint error, which is
-- the behaviour we want: instruments are reference data ingested from Twelve
-- Data, and one disappearing while users have it saved is a problem to look at,
-- not something to silently clean up.
--
-- added_at exists so the list has a stable order (oldest first). Without it the
-- row order is whatever Postgres feels like, which can change between reads and
-- makes the watchlist appear to shuffle itself. Stored in UTC like every other
-- timestamp in this schema -- see NOTE 1 below.
--
-- No SQL function for adding or reading the list, for the same reason as the
-- rest of this file: the app queries through Spring Data, and the functions
-- here are reference only.


-- UC04 (SCRUM-78): simulated trades. Every buy and sell a user places on the
-- demo-trading page, and the price it actually executed at.

CREATE TABLE trade (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT        NOT NULL REFERENCES app_user(id) ON DELETE CASCADE,
    symbol      VARCHAR(20)   NOT NULL REFERENCES instrument(symbol),
    side        VARCHAR(4)    NOT NULL CHECK (side IN ('BUY', 'SELL')),
    quantity    NUMERIC(18,8) NOT NULL CHECK (quantity > 0),
    price       NUMERIC(18,5) NOT NULL CHECK (price > 0),
    executed_at TIMESTAMP     NOT NULL DEFAULT (NOW() AT TIME ZONE 'UTC')
);

CREATE INDEX idx_trade_user_symbol ON trade (user_id, symbol, executed_at);
-- THERE IS DELIBERATELY NO `position` TABLE. A user's open quantity and average
-- cost are DERIVED by replaying their trade rows in order (see get_position()
-- below, and TradeService in the Java). The alternative -- a position row kept
-- in step on every execution -- makes reads a single lookup and costs the one
-- thing this schema has refused three times now: two copies of a fact that can
-- disagree. A position that has drifted from the trades behind it is invisible
-- until the numbers stop adding up, and afterwards there is no way to tell which
-- copy was right. With one instrument and a handful of rows per user, the
-- replay is free. Same reasoning as the single price_candle table.
--
-- quantity is NUMERIC(18,8) while every money column in this schema is
-- NUMERIC(18,5), and that difference is the point. BTC trades around $76,000, so
-- $100 of it is about 0.0013 BTC. At five decimal places that stores as
-- 0.00132 -- the order is rounded before it is even written, and a small enough
-- buy rounds to zero. Eight decimals is the crypto convention (one satoshi is
-- 1e-8). "How precisely can a price be quoted" and "how small a fraction of an
-- asset can be held" are different questions; giving them the same answer only
-- looks tidy.
--
-- price is the price this trade EXECUTED at, captured at that moment. It is
-- deliberately not a foreign key to a price_candle row: a candle summarises a
-- whole minute, and the trade happened at one instant inside it. This is the
-- only price in the entire application that is persisted for its own sake --
-- price_candle rows are a cache that can be re-fetched from Twelve Data, and the
-- live chart is a memory window that ages out in half an hour, but "what did I
-- pay?" is true only at the instant it happened and no provider can be asked for
-- it later. The chart is scenery; this is a fact.
--
-- side is a VARCHAR with a CHECK rather than a Postgres ENUM, for the same
-- reason price_candle.interval is: a CHECK is one line to change and maps onto a
-- Java enum with no special JDBC handling, where a real CREATE TYPE needs a
-- migration to add a value and a converter on the Java side. If short selling is
-- ever added (UC04 BR4 says no margin and no short selling), this is one edit.
--
-- CHECK (quantity > 0), not >= 0: a zero-quantity trade is not a trade, and
-- letting one in puts rows into every later SUM that mean nothing. CHECK
-- (price > 0) is the same guard one level up -- it is what stops Finnhub's
-- {"c":0} "success" response, or a bug that reads a missing price as zero, from
-- being written as a real fill.
--
-- ON DELETE CASCADE on user_id matches watchlist: deleting an account takes its
-- trade history with it, because an orphaned trade points at a user id that no
-- longer exists and is invisible to every query. No cascade on symbol, also like
-- watchlist -- deleting an instrument somebody has traded should fail loudly
-- rather than silently erase their history.
--
-- The index is (user_id, symbol, executed_at) in that order because every read
-- is "this user's trades for this symbol, oldest first" -- which is exactly the
-- replay get_position() does -- so one index covers the filter and the sort
-- together. executed_at alone would not help; user_id alone would still need a
-- sort.
--
-- There is no `total` or `cost` column. It is price * quantity, derivable
-- exactly, and a stored copy is one more thing that can disagree.
--
-- executed_at is UTC like every other timestamp here (NOTE 1 below). The ORDER
-- BY in get_position() breaks ties on id, because two trades can land in the
-- same millisecond and the replay must still be deterministic.
--
-- THE OTHER HALF OF THIS FEATURE IS app_user.cash_balance. A buy inserts a row
-- here and debits that column; a sell inserts a row and credits it. Those two
-- writes happen in ONE transaction in the service layer (@Transactional) -- a
-- trade row without its cash movement, or the reverse, is a portfolio that does
-- not add up and cannot be repaired afterwards. The CHECK (cash_balance >= 0) on
-- app_user is the backstop; the readable "not enough virtual funds" error comes
-- from the service.




-- UC05 (SCRUM-81): the trading journal. One row = one note a user wrote, with
-- an optional link to an instrument and an optional link to one of their own
-- trades.

CREATE TABLE journal_entry (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT      NOT NULL REFERENCES app_user(id) ON DELETE CASCADE,
    body       TEXT        NOT NULL CHECK (length(btrim(body)) > 0),
    symbol     VARCHAR(20)     NULL REFERENCES instrument(symbol),
    trade_id   BIGINT          NULL REFERENCES trade(id),
    created_at TIMESTAMP   NOT NULL DEFAULT (NOW() AT TIME ZONE 'UTC'),
    updated_at TIMESTAMP       NULL
);

CREATE INDEX idx_journal_user_created ON journal_entry (user_id, created_at DESC);
-- THERE ARE DELIBERATELY NO PRICE OR SIGNAL COLUMNS HERE, and the absence is
-- the decision -- which is why it is written down rather than merely not
-- present. UC05 step 6 originally specified that submitting an entry snapshots
-- the instrument's current price and signal at that moment. That was dropped on
-- 2026-09-22, before any of it was built.
--
-- The reason is the trade link two lines up. A trade row already carries the
-- exact price and the exact instant it executed at, captured by the server. A
-- snapshot stored beside it would be a SECOND record of the same moment, and
-- this schema has now refused that three times (no position table, no total
-- column, one price_candle table): when two records of one moment disagree
-- there is no way to tell afterwards which was right. After this change the
-- whole schema has exactly ONE place where a price is stored for its own sake,
-- trade.price, and its justification is written on that table.
--
-- The cost, stated rather than left to be discovered: an entry that links an
-- instrument but NO trade no longer records what that instrument was worth when
-- it was written. That is accepted. An entry that wants to say "this is what
-- the market was doing" links a trade; an entry that does not is a note, and a
-- note does not need a price.
--
-- trade_id has NO cascade -- the default NO ACTION. Deleting a trade that an
-- entry points at fails loudly, exactly like watchlist.symbol and trade.symbol.
-- Nothing in the application deletes a trade and nothing is planned to; this
-- constraint is what will stop that silently orphaning somebody's writing if it
-- is ever added, and the behaviour can be decided then with the case actually
-- in front of us rather than guessed at now.
--
-- user_id DOES cascade, and the asymmetry is deliberate. Deleting an account
-- takes its journal with it, because those entries belong to nobody afterwards.
-- Deleting a trade is a different question, answered above. Note that an
-- account deletion removes the trades and the entries together, so it cannot
-- produce the orphan case either.
--
-- symbol and trade_id are BOTH nullable and independent. The common entry --
-- "I keep buying tops, slow down" -- links neither. An entry may name an
-- instrument without a trade (a thought about the market), and the app always
-- fills in symbol when it fills in trade_id, but the DB does not force that:
-- a CHECK tying them together would buy nothing and would have to be relaxed
-- the first time a note is attached to a trade whose instrument was renamed.
--
-- body is TEXT, not VARCHAR(n). Postgres stores the two identically, so a
-- length cap would be an arbitrary number nobody can defend, and the failure it
-- creates -- somebody's long entry truncated or rejected -- is worse than a
-- long row. The CHECK on the TRIMMED length is UC05 5a at the last line of
-- defence: a body of only spaces is not an entry. The readable 400 comes from
-- JournalService; this is the backstop for anything that reaches the table
-- another way.
--
-- updated_at is NULL until the first edit, and is NOT set equal to created_at
-- on insert. Setting it would look tidier and would destroy the only thing the
-- column is for: you could no longer tell "never edited" from "edited
-- instantly". Same instinct as app_user.cash_balance keeping five decimals --
-- the tidy-looking choice loses information the feature needs.
--
-- The index is (user_id, created_at DESC) because every read of this table is
-- "my journal, newest first" and that is the entire access pattern. The DESC is
-- in the index rather than left to a sort: the list endpoint has no other
-- ordering and never will, since a journal is read in the order it was written.
--
-- created_at and updated_at are UTC like every other timestamp here (NOTE 1).


