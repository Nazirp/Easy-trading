-- Reports whether we have usable price data for a symbol at a given interval, so
-- the business logic layer knows whether it needs to trigger ingestion from
-- Twelve Data before showing a chart (UC01 step 10 / extension 10a: "fetches (or
-- reuses cached) current price/chart data... falls back to cached data with an
-- outdated notice, or an error state if nothing is cached").
--
-- Returns one of:
--   'MISSING'      -> zero rows for this symbol+interval: nothing to show,
--                      a full fetch is needed.
--   'INSUFFICIENT' -> some rows exist, but either too few to plot a meaningful
--                      chart (< min_candles) or the newest candle is older than
--                      that interval's own staleness threshold (we're missing at
--                      least the most recent candle).
--   'OK'           -> enough recent data, serve straight from cache.
--
-- MISSING and INSUFFICIENT both mean "call ingestion" as far as the caller is
-- concerned -- they're only split out so ingestion/logging can tell "nothing at
-- all" apart from "have something, but it's stale or too thin".
--
-- Now takes p_interval, since price_candle holds all four intervals: asking
-- "do we have data for EUR/USD" is meaningless without saying at which interval.
-- An unknown interval raises rather than returning a value, so a typo surfaces
-- immediately instead of masquerading as MISSING.
--
-- NOTE 1: TIMEZONE CONVENTION -- intraday (2h, 4h) `datetime` values are UTC;
-- 1day and 1week values are the exchange's trading date, with no meaningful time
-- of day. This is guaranteed at ingestion: the Twelve Data request sends
-- timezone=UTC, which that API applies to intraday intervals and ignores for
-- daily/weekly. It is NOT an assumption -- it was one until 2026-09-08, and it
-- was wrong: the parameter defaults to "Exchange", so candles were arriving on
-- each instrument's own exchange clock. NOW() here is timestamptz and is
-- compared via the session's timezone setting; the Java side does the same
-- comparison explicitly in UTC (PriceService.needsIngestion).
--
-- NOTE 2: the staleness threshold is exactly one interval, which is strict.
-- Forex and stock markets close on weekends, so on a Sunday the newest 4h candle
-- is legitimately hours old and this reports INSUFFICIENT, triggering an
-- ingestion call that finds nothing new. If that turns into wasted Twelve Data
-- requests against the 800/day cap, widen the thresholds (e.g. 1.5x the interval)
-- or make them market-hours aware.
--
-- CORRECTED 2026-09-21: the Java side did exactly that -- Interval
-- .stalenessThreshold() has been 1.5x the candle length since the range
-- switcher landed. This function was left at 1x, and '2h' was missing from the
-- CASE above entirely (added 2026-09-21), so calling it for the 1w range raised
-- "Unknown interval" while the price_candle CHECK accepted 2h rows happily.
-- Nothing broke, because nothing calls this -- which is the REFERENCE ONLY
-- banner earning its keep, and also the exact drift it warns about. The Java is
-- authoritative; this function is now correct about the interval set and still
-- deliberately stricter about staleness.
DROP FUNCTION IF EXISTS check_price_data(VARCHAR);  -- the old 1-arg version; CREATE OR REPLACE
                                                    -- below would otherwise ADD an overload
                                                    -- rather than replace it, leaving both live
CREATE OR REPLACE FUNCTION check_price_data(p_symbol VARCHAR, p_interval VARCHAR)
RETURNS VARCHAR AS $$
DECLARE
    row_count            INTEGER;
    latest_dt            TIMESTAMP;
    staleness_threshold  INTERVAL;
    min_candles          CONSTANT INTEGER := 2;
BEGIN
    staleness_threshold := CASE p_interval
        WHEN '2h'    THEN INTERVAL '2 hours'
        WHEN '4h'    THEN INTERVAL '4 hours'
        WHEN '1day'  THEN INTERVAL '1 day'
        WHEN '1week' THEN INTERVAL '7 days'
    END;

    IF staleness_threshold IS NULL THEN
        RAISE EXCEPTION 'Unknown interval: %. Expected one of 2h, 4h, 1day, 1week.', p_interval;
    END IF;

    SELECT COUNT(*), MAX(c.datetime) INTO row_count, latest_dt
    FROM price_candle c
    WHERE c.symbol = p_symbol
      AND c.interval = p_interval;

    IF row_count = 0 THEN
        RETURN 'MISSING';
    ELSIF row_count < min_candles OR latest_dt < (NOW() - staleness_threshold) THEN
        RETURN 'INSUFFICIENT';
    ELSE
        RETURN 'OK';
    END IF;
END;
$$ LANGUAGE plpgsql;

-- The open position for one user and one instrument (UC04), derived from the
-- trade rows rather than stored. REFERENCE ONLY, like everything in this
-- section -- the application computes this in Java (TradeService), because the
-- same replay also has to produce the cash balance and the unrealised P&L that
-- ride in the /api/getLiveChart response.
--
-- AVERAGE-COST METHOD: a BUY moves the weighted average, a SELL reduces the
-- quantity and leaves the average alone. FIFO lot tracking is what a real broker
-- does and is more accurate about realised gains; average cost is what a
-- beginner expects when a screen says "your average price", and it keeps that
-- number stable instead of jumping every time part of a holding is sold. UC04's
-- audience decided the arithmetic.
--
-- Selling out completely resets the average to 0 rather than leaving the last
-- one behind, so "no position" is one state and not two.
--
-- CAVEAT, because it matters to the frontend and this function does NOT express
-- it: a user who has never traded and a user who bought and then sold out both
-- come back from here as 0 | 0. The API distinguishes them -- /api/getLiveChart
-- sends `account: null` for someone with no trades at all, and an account block
-- with quantity 0 for someone who traded and closed out -- because "you have no
-- position" and "your P&L is 0.00" are different sentences and a beginner reading
-- the second one would reasonably think they still own something. Do not read
-- this function as the spec for that; it is the arithmetic only.
CREATE OR REPLACE FUNCTION get_position(p_user_id BIGINT, p_symbol VARCHAR)
RETURNS TABLE (open_quantity NUMERIC, average_cost NUMERIC) AS $$
DECLARE
    t        RECORD;
    qty      NUMERIC(18,8) := 0;
    avg_cost NUMERIC(18,5) := 0;
BEGIN
    FOR t IN
        SELECT tr.side       AS side,
               tr.quantity   AS trade_qty,
               tr.price      AS trade_price
        FROM trade tr
        WHERE tr.user_id = p_user_id
          AND tr.symbol  = p_symbol
        ORDER BY tr.executed_at, tr.id
    LOOP
        IF t.side = 'BUY' THEN
            avg_cost := (qty * avg_cost + t.trade_qty * t.trade_price)
                        / (qty + t.trade_qty);
            qty      := qty + t.trade_qty;
        ELSE
            qty := qty - t.trade_qty;
            IF qty <= 0 THEN
                qty      := 0;
                avg_cost := 0;
            END IF;
        END IF;
    END LOOP;

    RETURN QUERY SELECT qty, avg_cost;
END;
$$ LANGUAGE plpgsql;


-- One user's journal, newest first (UC05 steps 8-9). REFERENCE ONLY: the
-- application reads this through JournalRepository, not through here.
--
-- The parameter is the user id and there is no variant without it. That is the
-- point of the function rather than an oversight: an entry id is a small
-- integer and therefore guessable, so every read of this table in the
-- application is scoped by owner IN THE QUERY -- findByIdAndUserId, never
-- findById followed by a comparison in Java. The second shape reads somebody
-- else's row into memory first, which is one careless log line away from
-- leaking it, and it invites a later refactor to drop the check. This function
-- is written the same way so the DB-side statement of the rule does not quietly
-- disagree with the Java one.
--
-- symbol and trade_id come back as they are stored, including NULL. The join to
-- instrument or trade is the caller's business; resolving it here would make
-- this function a second implementation of what JournalService already does.
CREATE OR REPLACE FUNCTION get_journal(p_user_id BIGINT)
RETURNS TABLE (
    id         BIGINT,
    body       TEXT,
    symbol     VARCHAR(20),
    trade_id   BIGINT,
    created_at TIMESTAMP,
    updated_at TIMESTAMP
) AS $$
BEGIN
    RETURN QUERY
    SELECT j.id,
           j.body,
           j.symbol,
           j.trade_id,
           j.created_at,
           j.updated_at
    FROM journal_entry j
    WHERE j.user_id = p_user_id
    ORDER BY j.created_at DESC, j.id DESC;
END;
$$ LANGUAGE plpgsql;
-- ORDER BY breaks ties on id for the same reason get_position() does: two
-- entries written in the same millisecond must still come back in a stable
-- order, or the list appears to shuffle between two identical reads.


